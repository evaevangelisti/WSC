"""
Command-level inference, cached replay, and input preservation.
"""

import json
from collections.abc import Sequence
from pathlib import Path

import pytest
from typer.testing import CliRunner

from wsc import cli
from wsc.models.alignment import AlignmentInstructions, AlignmentTask, Comparison
from wsc.reading import read_alignments, read_lemmas, read_metadata
from wsc.upstream import cache


class Scorer:
    """Offline model boundary for command-level integration tests."""

    def __init__(
        self,
        model: str,
        *,
        revision: str,
        device: str | None,
        batch_size: int,
        maximum_length: int,
        instructions: AlignmentInstructions,
    ) -> None:
        """
        Accept the real cross-encoder configuration without loading weights.

        Args:
            model: Model identifier.
            revision: Model revision.
            device: Inference device.
            batch_size: Pair batch size.
            maximum_length: Token limit.
            instructions: Semantic instruction profile.
        """
        _ = model, revision, device, batch_size, maximum_length, instructions

    def score(self, pairs: Sequence[Comparison]) -> list[float]:
        """
        Supply positive translation evidence.

        Args:
            pairs: Actual hypotheses generated by the command.

        Returns:
            One positive score per candidate.
        """
        return [4.0] * len(pairs)


@pytest.mark.parametrize("tasks", [(AlignmentTask.TRANSLATIONS,), tuple(AlignmentTask)])
def test_command_replays_cached_scores_without_loading_model(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    tasks: tuple[AlignmentTask, ...],
) -> None:
    """A second alignment changes thresholds using TSV evidence alone."""
    source = tmp_path / "input.jsonl"
    original = (
        json.dumps(
            {
                "id": "word.noun",
                "lemma": "word",
                "pos": "noun",
                "senses": [{"id": "s", "glosses": ["meaning"]}],
                "translations": {"gloss": {"it": ["parola"]}},
            }
        )
        + "\n"
    )
    _ = source.write_text(original, encoding="utf-8")
    synsets_path = cache.wordnet_dir(tmp_path / "cache", "2025") / cache.SYNSETS_NAME
    synsets_path.parent.mkdir(parents=True)
    _ = synsets_path.write_text(
        json.dumps(
            {
                "id": "wordnet-sense",
                "ili": "i1",
                "pos": "noun",
                "definition": "meaning",
                "members": ["word"],
            }
        )
        + "\n",
        encoding="utf-8",
    )
    monkeypatch.setattr(cli, "CrossEncoderScorer", Scorer)
    arguments = [
        "align",
        str(source),
        str(tmp_path / "output.jsonl"),
        "--translation-threshold",
        "1",
        "--wordnet-threshold",
        "1",
        "--cache-dir",
        str(tmp_path / "cache"),
    ]
    for task in tasks:
        arguments.extend(("--task", task))
    first = CliRunner().invoke(cli.app, arguments)
    assert first.exit_code == 0, first.output
    assert len(list((tmp_path / "cache").glob("alignment/*/translations.tsv"))) == 1
    output = next(read_lemmas(tmp_path / "output.jsonl"))
    assert output.senses[0].translations == {"it": frozenset({"parola"})}
    assert not output.translations
    evidence_paths = list((tmp_path / "cache").glob("alignment/*/*.tsv"))
    assert {path.stem for path in evidence_paths} == set(tasks)
    for path in evidence_paths:
        assert read_metadata(path)["schema"] == "3"
        evidence = list(read_alignments(path))
        assert len(evidence) == 1
        assert evidence[0].query.alignment_id == (
            "s" if path.stem == "wordnet" else "word.noun"
        )
    if AlignmentTask.WORDNET in tasks:
        assert output.senses[0].wordnet[0].synset_id == "wordnet-sense"

    def reject_model(*_arguments: object, **_options: object) -> Scorer:
        raise AssertionError("Cached replay must not load a model")

    monkeypatch.setattr(cli, "CrossEncoderScorer", reject_model)
    arguments[arguments.index("1")] = "5"
    second = CliRunner().invoke(cli.app, [*arguments, "--reuse"])

    assert second.exit_code == 0, second.output
    assert source.read_text() == original
    assert not next(read_lemmas(tmp_path / "output.jsonl")).senses[0].translations


@pytest.mark.parametrize("task", list(AlignmentTask))
@pytest.mark.parametrize("threshold", ["nan", "inf", "-inf"])
def test_command_rejects_nonfinite_thresholds_before_reading_inputs(
    tmp_path: Path,
    task: AlignmentTask,
    threshold: str,
) -> None:
    """Nonfinite thresholds fail before reading inputs or loading models."""
    option = "translation" if task == AlignmentTask.TRANSLATIONS else "wordnet"
    result = CliRunner().invoke(
        cli.app,
        [
            "align",
            str(tmp_path / "missing.jsonl"),
            str(tmp_path / "output.jsonl"),
            "--task",
            task,
            f"--{option}-threshold",
            threshold,
        ],
    )

    assert result.exit_code != 0
    assert "Supply finite" in result.output
    assert not (tmp_path / "output.jsonl").exists()


def test_command_refuses_missing_threshold_before_loading_models(
    tmp_path: Path,
) -> None:
    """Uncalibrated defaults cannot silently assign the collection."""
    result = CliRunner().invoke(
        cli.app,
        [
            "align",
            str(tmp_path / "input.jsonl"),
            str(tmp_path / "output.jsonl"),
            "--task",
            "translations",
        ],
    )

    assert result.exit_code != 0
    assert "translation-threshold" in result.output
