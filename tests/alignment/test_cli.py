"""Exercise command-level inference and cached decision replay."""

import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from wsc import cli
from wsc.extract.identifiers import translation_table_id
from wsc.models.alignment import (
    AlignmentTask,
    LanguageModel,
    ModelRequest,
    ModelSettings,
)
from wsc.reading import read_alignments, read_lemmas
from wsc.upstream import cache


class Model:
    """Generate a valid association from the requested output schema."""

    def generate(
        self,
        request: ModelRequest,
    ) -> str:
        """
        Associate the source with its only candidate.

        Args:
            request: Model request generated by the command.

        Returns:
            A translation or equivalent WordNet association.
        """
        relation = (
            "translation"
            if "short translation definitions" in request.prompt
            else "equivalent"
        )
        target = (
            translation_table_id("word.noun", "gloss")
            if relation == "translation"
            else "wordnet-sense"
        )

        return json.dumps(
            {
                "s": [
                    {
                        "target_id": target,
                        "relation": relation,
                        "reason": "Same lexical meaning.",
                    },
                ],
            }
        )


@pytest.mark.parametrize("tasks", [(AlignmentTask.TRANSLATIONS,), tuple(AlignmentTask)])
def test_command_replays_decisions_without_loading_model(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    tasks: tuple[AlignmentTask, ...],
) -> None:
    """Cached replay preserves the aligned collection and original input."""
    source = tmp_path / "input.jsonl"
    original = (
        json.dumps(
            {
                "id": "word.noun",
                "lemma": "word",
                "pos": "noun",
                "senses": [{"id": "s", "glosses": ["meaning"], "synonyms": ["term"]}],
                "translation_tables": [
                    {
                        "id": translation_table_id("word.noun", "gloss"),
                        "gloss": "gloss",
                        "translations": {"it": ["parola"]},
                    }
                ],
            }
        )
        + "\n"
    )
    _ = source.write_text(original, encoding="utf-8")
    synsets_path = cache.wordnet_dir(tmp_path / "cache", "2025") / cache.SYNSETS_NAME
    synsets_path.parent.mkdir(parents=True)
    _ = synsets_path.write_text(
        json.dumps(
            {
                "id": "wordnet-sense",
                "ili": "i1",
                "pos": "noun",
                "definition": "meaning",
                "members": ["word"],
            }
        )
        + "\n",
        encoding="utf-8",
    )

    def load_model(
        settings: ModelSettings,
    ) -> LanguageModel:
        """
        Replace weight loading while retaining model settings.

        Args:
            settings: Command inference configuration.

        Returns:
            An offline language model.
        """
        assert settings.temperature == 0.0

        return Model()

    monkeypatch.setattr(cli, "open_model", load_model)
    arguments = [
        "align",
        str(source),
        str(tmp_path / "output.jsonl"),
        "--cache-dir",
        str(tmp_path / "cache"),
    ]

    for task in tasks:
        arguments.extend(("--task", task))

    first = CliRunner().invoke(cli.app, arguments)

    assert first.exit_code == 0, first.output
    output = next(read_lemmas(tmp_path / "output.jsonl"))
    assert output.senses[0].translations == {"it": frozenset({"parola"})}
    assert not output.translation_tables

    if AlignmentTask.WORDNET in tasks:
        assert output.senses[0].wordnet[0].synset_id == "wordnet-sense"

    paths = list((tmp_path / "cache").glob("alignment/*/*.tsv"))
    assert {path.stem for path in paths} == set(tasks)
    assert all(next(read_alignments(path)).response for path in paths)
    evidence = {path: path.read_bytes() for path in paths}

    def reject_model(
        settings: ModelSettings,
    ) -> LanguageModel:
        """
        Fail if replay attempts model inference.

        Args:
            settings: Unexpected model configuration.

        Raises:
            AssertionError: If a model is loaded.
        """
        raise AssertionError(f"Unexpected model loading: {settings.model}")

    monkeypatch.setattr(cli, "open_model", reject_model)
    second = CliRunner().invoke(cli.app, [*arguments, "--reuse"])

    assert second.exit_code == 0, second.output
    assert next(read_lemmas(tmp_path / "output.jsonl")) == output
    assert source.read_text() == original
    assert {path: path.read_bytes() for path in paths} == evidence

    changed = CliRunner().invoke(
        cli.app, [*arguments, "--temperature", "0.5", "--reuse"]
    )

    assert changed.exit_code != 0
    assert "No compatible alignment cache" in changed.output


def test_command_exposes_generation_options_without_score_thresholds() -> None:
    """The command accepts language model settings and two gloss modes."""
    result = CliRunner().invoke(cli.app, ["align", "--help"])
    output = " ".join(result.output.split())

    assert result.exit_code == 0
    assert "temperature" in output
    assert "engine-option" in output
    assert "provider-temperature" not in output
    assert "threshold" not in output
    assert "context" not in output


def test_command_preserves_input_when_output_path_matches(
    tmp_path: Path,
) -> None:
    """In-place alignment fails before loading models."""
    source = tmp_path / "input.jsonl"
    _ = source.write_text("original", encoding="utf-8")
    result = CliRunner().invoke(cli.app, ["align", str(source), str(source)])

    assert result.exit_code != 0
    assert source.read_text() == "original"
