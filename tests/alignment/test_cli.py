def test_reuses_partial_alignment_cache(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """
    Reuse requests only sources absent from the task TSV.
    """
    input_path = tmp_path / "input.jsonl"
    first_target = translation_table_id("word.noun", "first")
    second_target = translation_table_id("word.noun", "second")
    _ = input_path.write_text(
        json.dumps(
            {
                "id": "word.noun",
                "lemma": "word",
                "pos": "noun",
                "senses": [
                    {"id": "s1", "glosses": ["first"]},
                    {"id": "s2", "glosses": ["second"]},
                ],
                "translation_tables": [
                    {
                        "id": first_target,
                        "gloss": "first",
                        "translations": {"it": ["uno"]},
                    },
                    {
                        "id": second_target,
                        "gloss": "second",
                        "translations": {"it": ["due"]},
                    },
                ],
            },
        )
        + "\n",
        encoding="utf-8",
    )

    cache_path = tmp_path / "cache" / "alignment" / "translations.tsv"
    cache_path.parent.mkdir(parents=True)

    with cache_path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream, delimiter="\t")
        writer.writerow(ALIGNMENT_FIELDS)
        writer.writerow(
            (
                "translations:word.noun",
                "s1",
                first_target,
                "translation",
                "The definitions express the same concept.",
            ),
        )

    model = Model(
        json.dumps(
            {
                "s2": [
                    {
                        "target_id": second_target,
                        "relation": "translation",
                        "reason": "The definitions express the same concept.",
                    },
                ],
            },
        ),
    )

    def load_model(
        settings: ModelSettings,
    ) -> LanguageModel:
        """
        Return the partial reuse model after deferred loading.

        Args:
            settings: Command inference configuration.

        Returns:
            Model recording the missing-source request.
        """
        del settings

        return model

    monkeypatch.setattr(cli, "open_model", load_model)

    result = CliRunner().invoke(
        cli.app,
        [
            "align",
            str(input_path),
            "--output-dir",
            str(tmp_path / "output"),
            "--task",
            "translations",
            "--cache-dir",
            str(tmp_path / "cache"),
            "--reuse",
        ],
    )

    assert result.exit_code == 0, result.output
    assert len(model.requests) == 1
    assert model.requests[0].schema["required"] == ["s2"]
    assert first_target not in model.requests[0].prompt
    assert second_target in model.requests[0].prompt

    (aligned,) = tuple(read_lemmas(tmp_path / "output" / "senses.jsonl"))

    assert aligned.senses[0].translation_table == TranslationTable(
        first_target,
        "first",
        {Language("it"): frozenset({"uno"})},
    )
    assert aligned.senses[1].translation_table == TranslationTable(
        second_target,
        "second",
        {Language("it"): frozenset({"due"})},
    )
    assert len(cache_path.read_text().splitlines()) == 3


@given(
    interrupt_with_signal=st.booleans(),
    reuse=st.booleans(),
)
def test_resumes_after_interrupted_inference(
    workspace: Callable[[], Path],
    monkeypatch: pytest.MonkeyPatch,
    *,
    interrupt_with_signal: bool,
    reuse: bool,
) -> None:
    """
    Model failure and SIGTERM preserve recorded decisions in either cache mode.
    """
    tmp_path = workspace()
    input_path = tmp_path / "input.jsonl"
    targets = {
        word: translation_table_id(f"{word}.noun", word) for word in ("first", "second")
    }
    records = (
        {
            "id": f"{word}.noun",
            "lemma": word,
            "pos": "noun",
            "senses": [{"id": f"{word}.noun.1", "glosses": [word]}],
            "translation_tables": [
                {
                    "id": targets[word],
                    "gloss": word,
                    "translations": {"it": [word]},
                },
            ],
        }
        for word in targets
    )
    _ = input_path.write_text(
        "".join(f"{json.dumps(record)}\n" for record in records),
        encoding="utf-8",
    )

    class FailingModel(Model):
        """
        Fail after one completed translation decision.
        """

        @override
        def generate_batch(
            self,
            requests: Sequence[ModelRequest],
        ) -> tuple[ModelOutcome, ...]:
            """
            Return one decision before simulating an engine failure.

            Args:
                requests: Single-request batch supplied by the aligner.

            Returns:
                First successful outcome in submission order.

            Raises:
                RuntimeError: When the second batch is submitted.
                AssertionError: If SIGTERM does not interrupt inference.
            """
            self.requests.extend(requests)

            if len(self.requests) > 1:
                if interrupt_with_signal:
                    signal.raise_signal(signal.SIGTERM)

                    raise AssertionError("SIGTERM did not interrupt inference")

                raise RuntimeError("engine died")

            return (
                ModelOutcome(
                    json.dumps(
                        {
                            "first.noun.1": [
                                {
                                    "target_id": targets["first"],
                                    "relation": "translation",
                                    "reason": "Same meaning.",
                                },
                            ],
                        },
                    ),
                ),
            )

    failing_model = FailingModel()

    def load_failing_model(
        settings: ModelSettings,
    ) -> LanguageModel:
        """
        Return the model that fails on its second request.

        Args:
            settings: Unused inference configuration.

        Returns:
            The test model.
        """
        del settings

        return failing_model

    monkeypatch.setattr(cli, "open_model", load_failing_model)
    arguments = [
        "align",
        str(input_path),
        "--task",
        "translations",
        "--batch-size",
        "1",
        "--cache-dir",
        str(tmp_path / "cache"),
        "--output-dir",
        str(tmp_path / "output"),
    ]

    previous_handler = signal.signal(signal.SIGTERM, signal.SIG_IGN)

    try:
        failed = CliRunner().invoke(
            cli.app,
            [*arguments, "--reuse"] if reuse else arguments,
        )

        assert signal.getsignal(signal.SIGTERM) == signal.SIG_IGN
    finally:
        _ = signal.signal(signal.SIGTERM, previous_handler)

    assert failed.exit_code != 0

    if interrupt_with_signal:
        assert failed.exit_code == 143
        assert isinstance(failed.exception, SystemExit)
    else:
        assert isinstance(failed.exception, RuntimeError)
        assert str(failed.exception) == "engine died"

    assert failed.exception.__notes__ == [
        "Failed alignment batch (1): translations:second.noun"
    ]

    cache_path = tmp_path / "cache" / "alignment" / "translations.tsv"
    assert cache_path.exists()
    assert not list(cache_path.parent.glob("*.part"))
    assert set(read_alignment_cache(cache_path)) == {"translations:first.noun"}

    class ResumeModel(Model):
        """
        Resolve only the still-uncached second lemma.
        """

        @override
        def generate_batch(
            self,
            requests: Sequence[ModelRequest],
        ) -> tuple[ModelOutcome, ...]:
            """
            Return the remaining translation association.

            Args:
                requests: Single uncached alignment request.

            Returns:
                One successful model outcome.
            """
            self.requests.extend(requests)

            return (
                ModelOutcome(
                    json.dumps(
                        {
                            "second.noun.1": [
                                {
                                    "target_id": targets["second"],
                                    "relation": "translation",
                                    "reason": "Same meaning.",
                                },
                            ],
                        },
                    ),
                ),
            )

    resume_model = ResumeModel()

    def load_resume_model(
        settings: ModelSettings,
    ) -> LanguageModel:
        """
        Return the model resolving the remaining request.

        Args:
            settings: Unused inference configuration.

        Returns:
            The test model.
        """
        del settings

        return resume_model

    monkeypatch.setattr(cli, "open_model", load_resume_model)

    resumed = CliRunner().invoke(cli.app, [*arguments, "--reuse"])

    assert resumed.exit_code == 0, resumed.output
    assert signal.getsignal(signal.SIGTERM) == previous_handler
    assert len(resume_model.requests) == 1
    assert resume_model.requests[0].schema["required"] == ["second.noun.1"]
    assert set(read_alignment_cache(cache_path)) == {
        "translations:first.noun",
        "translations:second.noun",
    }
